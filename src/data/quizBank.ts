export function getQuizQuestionsForConfig(
  subject: Subject,
  classLevel: number,
  chapter: string,
  difficulty: Difficulty,
  count = 5
): QuizQuestion[] {
  const bySubject = QUIZ_BANK.filter((q) => q.subject === subject);
  const exact = bySubject.filter((q) => q.chapter === chapter || q.difficulty === difficulty);
  const pool = [...exact, ...bySubject, ...QUIZ_BANK];

  const seen = new Set<string>();
  const result: QuizQuestion[] = [];
  for (const q of pool) {
    if (seen.has(q.id)) continue;
    seen.add(q.id);
    result.push({ ...q, classLevel });
    if (result.length >= count) break;
  }
  return result;
}
